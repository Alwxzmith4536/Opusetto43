# Main
# -----------------------------------------------------------------------------

def main():
    reset_scene()
    scene = bpy.context.scene
    scene.name = 'Saitama vs Cosmic Garou'
    setup_render(scene)
    world = World(scene)
    env = collection('Environment')
    chars = collection('Characters')
    s_coll = collection('Saitama', chars)
    g_coll = collection('Garou', chars)
    ghosts_coll = collection('Saitama_Afterimages', chars)
    cam_coll = collection('Camera')

    ground_me = disc_mesh('GroundMesh', 1.0, 64)
    ground_me.materials.append(toon_mat('Ground', (1.0, 1.0, 1.0), 0.84, (0.93, 0.95, 1.0)))
    ground = new_obj('Ground', ground_me, env)
    ground.scale = (400, 400, 1)
    sun_d = bpy.data.lights.new('Sun', 'SUN')
    sun_d.energy = 2.6
    sun_d.angle = rad(3)
    sun = new_obj('Sun', sun_d, env)
    sun.rotation_euler = (rad(38), rad(8), rad(35))

    S = build_saitama('Saitama', s_coll, saitama_materials())
    cache_rest(S.rig)
    G = build_garou('CosmicGarou', g_coll, garou_materials())
    fx = FX()
    ghost_mat = fx.flat
    for i in range(10):
        g = build_saitama('SaitamaGhost%02d' % i, ghosts_coll, None, ghost_mat=ghost_mat)
        for ob, key in g.tags:
            if hasattr(ob, 'visible_shadow'):
                ob.visible_shadow = False
            key_col(ob, 0, S_COLORS[key], 0.0)
        g.place(0, (0, 0, -50), interp='CONSTANT')
        for b in CAPE_BONES:
            pb = g.rig.pose.bones[b[0]]
            pb.rotation_euler = (rad(-35), 0, 0)
            pb.keyframe_insert('rotation_euler', frame=0)
        fx.ghost_pool.append(g)

    cam = CameraRig(cam_coll)
    info = choreograph(S, G, fx, world, cam)

    # halo spin + orbiting stars, constant speed for the whole film
    for ob, axis, turns in ((G.extra['halo_pivot'], 1, 60), (G.extra['orbiters'], 2, -45)):
        for f, a in ((1, 0.0), (END, turns * 2 * math.pi)):
            e = ob.rotation_euler.copy()
            e[axis] = a
            ob.rotation_euler = e
            ob.keyframe_insert('rotation_euler', frame=f)
    set_all_interp(G.extra['halo_pivot'], 'LINEAR')
    set_all_interp(G.extra['orbiters'], 'LINEAR')
    # halo scale keys should still ease
    for fc in fcurves_of(G.extra['halo_pivot']):
        if fc.data_path == 'scale':
            for kp in fc.keyframe_points:
                kp.interpolation = 'BEZIER'

    # fade in / fade out through a white card in front of the lens
    card = new_obj('FadeCard', disc_mesh('FadeCardMesh', 1.0, 16), cam_coll)
    card.data.materials.append(fx.flat)
    card.parent = cam.cam
    card.location = (0, 0, -0.06)
    card.scale = (0.2, 0.2, 0.2)
    if hasattr(card, 'visible_shadow'):
        card.visible_shadow = False
    for f, a in ((1, 1.0), (30, 0.0), (info['fade_start'], 0.0), (END, 1.0)):
        key_col(card, f, CARD, a)

    apply_interp_requests()
    for coll in (fx.coll, fx.debris):
        for ob in coll.objects:
            set_all_interp(ob, 'LINEAR')
    for g in fx.ghost_pool:
        for ob, _k in g.tags:
            set_all_interp(ob, 'LINEAR')
    for idb in (world.world.node_tree,):
        set_all_interp(idb, 'CONSTANT')
    set_all_interp(card, 'LINEAR')

    bake_cape(S)
    bake_camera(cam, {'S': S, 'G': G})
    setup_freestyle(scene, [s_coll, g_coll, fx.debris])
    scene.frame_set(1)

    here = os.path.dirname(os.path.abspath(__file__)) if '__file__' in globals() else os.getcwd()
    if bpy.app.background:
        out = os.environ.get('SVG_OUT') or os.path.join(here, 'saitama_vs_cosmic_garou.blend')
        bpy.ops.wm.save_as_mainfile(filepath=out, compress=True)
        print('Saved', out)
    print('Done: %d frames (%.1f s).' % (END, END / FPS))


if __name__ == '__main__':
    main()
