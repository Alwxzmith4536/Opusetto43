def ghost(fx, f, loc, yaw, pose, pitch=0.0, dur=14, a0=0.5):
    g = fx.ghost_pool[fx.ghost_i % len(fx.ghost_pool)]
    fx.ghost_i += 1
    g.place(f - 1, (0, 0, -50), yaw=yaw, interp='CONSTANT')
    g.place(f, loc, yaw=yaw, pitch=pitch, interp='CONSTANT')
    g.place(f + dur + 1, (0, 0, -50), yaw=yaw, interp='CONSTANT')
    g.pose(f, pose, interp='CONSTANT')
    for ob, key in g.tags:
        c = S_COLORS[key]
        key_col(ob, f - 1, c, 0.0)
        key_col(ob, f, c, a0)
        key_col(ob, f + dur, c, 0.0)


