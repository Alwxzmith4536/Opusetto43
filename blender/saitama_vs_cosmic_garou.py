INTERP = {}   # (obj name, kind) -> {frame: interpolation}


def want_interp(ob, kind, f, mode):
    INTERP.setdefault((ob.name, kind), {})[int(f)] = mode


def fcurves_of(id_):
    ad = getattr(id_, 'animation_data', None)
    if not ad or not ad.action:
        return []
    act = ad.action
    try:
        from bpy_extras import anim_utils
        cb = anim_utils.action_get_channelbag_for_slot(act, ad.action_slot)
        if cb is not None:
            return list(cb.fcurves)
    except Exception:
        pass
    return list(getattr(act, 'fcurves', []))


def set_all_interp(id_, mode):
    for fc in fcurves_of(id_):
        for kp in fc.keyframe_points:
            kp.interpolation = mode


def apply_interp_requests():
    for (name, kind), frames in INTERP.items():
        ob = bpy.data.objects[name]
        for fc in fcurves_of(ob):
            dp = fc.data_path
            if kind == 'loc' and dp not in ('location', 'rotation_euler'):
                continue
            if kind == 'pose' and not dp.startswith('pose.bones'):
                continue
            if kind == 'vis' and not dp.startswith('hide'):
                continue
            for kp in fc.keyframe_points:
                m = frames.get(int(round(kp.co.x)))
                if m:
                    kp.interpolation = m


class Evaluator:
    """Reads back what the fcurves really do (after interpolation fix-ups)."""

    def __init__(self, ob):
        self.c = {}
        for fc in fcurves_of(ob):
            self.c[(fc.data_path, fc.array_index)] = fc
        self.ob = ob

    def vec(self, path, f, default):
        return Vector([self.c[(path, i)].evaluate(f) if (path, i) in self.c else default[i]
                       for i in range(3)])

    def loc(self, f):
        return self.vec('location', f, self.ob.location)

    def rot(self, f):
        return self.vec('rotation_euler', f, self.ob.rotation_euler)


