    near = ground + (Sp - ground).normalized() * 2.6
    S.pose(f0, 'idle')
    S.place(f0 + 10, Sp, face=ground)
    fw, step = f0 + 20, 0
    walk_end = f0 + 120
    while fw < walk_end:
        S.place(fw, Sp.lerp(near, (fw - f0 - 20) / 100), face=ground, interp='LINEAR')
        S.pose(fw, 'walk_a' if step % 2 == 0 else 'walk_b')
        step += 1
        fw += 10
    S.place(walk_end, near, face=ground)
    S.pose(walk_end + 4, 'idle_down')
    S.pose(walk_end + 120, 'idle_down')
    G.pose(walk_end + 150, 'ko', armR=(40, 50, 0), foreR=60)
    G.pose(walk_end + 170, 'ko')
    S.pose(walk_end + 170, 'scratch')
    S.pose(walk_end + 230, 'scratch', foreR=130)
    S.pose(walk_end + 245, 'idle')
    leave = walk_end + 270
    exit_dir = (near - ground).normalized()
    exit_dir = Vector((-exit_dir.y, exit_dir.x, 0)) * 0.6 + exit_dir * 0.8
    far = near + exit_dir.normalized() * 22
    S.place(leave, near, face=far)
    fw, step = leave + 8, 0
    while fw < END - 10:
        S.place(fw, near.lerp(far, (fw - leave - 8) / (END - 10 - leave - 8)), face=far, interp='LINEAR')
        S.pose(fw, 'walk_a' if step % 2 == 0 else 'walk_b')
        step += 1
        fw += 11
    S.place(END, far, face=far + exit_dir)
    cam.shot(f0, walk_end, ('S', (0, 0, 0.3)), ('orbit', 'mid', -40, -10, 9, 7, 1.8, 1.6), (32, 36))
    cam.shot(walk_end + 1, walk_end + 150, ('G', (0, 0, -0.3)), ('follow', 'G', (0.8, -1.2, 5.5), (0.6, -0.9, 4.5)), (30, 34))
    cam.shot(walk_end + 151, leave, ('S', (0, 0, 0.72)), ('rel', 'S', (0.2, 1.4, 0.75), (0.1, 1.1, 0.72)), (48, 52))
    cam.shot(leave + 1, END, ('S', (0, 0, 0.3)), ('follow', 'G', (-4, -12, 2.5), (-14, -34, 14)), (35, 30), ease=False)
    return {'fade_start': END - 96}


