class Pool:
    def __init__(self, factory):
        self.factory = factory
        self.items = []

    def get(self, f0, f1):
        for it in self.items:
            if all(f1 + 2 < a or f0 > b + 2 for a, b in it[1]):
                it[1].append((f0, f1))
                return it[0]
        ob = self.factory(len(self.items))
        ob.hide_render = ob.hide_viewport = True
        ob.keyframe_insert('hide_render', frame=0)
        ob.keyframe_insert('hide_viewport', frame=0)
        ob.color = (1, 1, 1, 0)
        ob.keyframe_insert('color', frame=0)
        if hasattr(ob, 'visible_shadow'):
            ob.visible_shadow = False
        self.items.append([ob, [(f0, f1)]])
        return ob


def show(ob, f0, f1):
    for v, f in ((False, f0), (True, f1 + 1)):
        ob.hide_render = ob.hide_viewport = v
        ob.keyframe_insert('hide_render', frame=f)
        ob.keyframe_insert('hide_viewport', frame=f)


def appear(ob, f):
    """Hidden until frame f, then stays."""
    for v, fr in ((True, 0), (False, f)):
        ob.hide_render = ob.hide_viewport = v
        ob.keyframe_insert('hide_render', frame=fr)
        ob.keyframe_insert('hide_viewport', frame=fr)


def key_tf(ob, f, loc=None, rot=None, scale=None):
    if loc is not None:
        ob.location = loc
        ob.keyframe_insert('location', frame=f)
    if rot is not None:
        ob.rotation_euler = rot
        ob.keyframe_insert('rotation_euler', frame=f)
    if scale is not None:
        ob.scale = scale if hasattr(scale, '__len__') else (scale, scale, scale)
        ob.keyframe_insert('scale', frame=f)


def key_col(ob, f, rgb, a):
    ob.color = (rgb[0], rgb[1], rgb[2], a)
    ob.keyframe_insert('color', frame=f)


def align_euler(normal):
    return Vector((0, 0, 1)).rotation_difference(Vector(normal).normalized()).to_euler()


