    def portal(self, f0, f1, loc, normal, size=1.4):
        ring = self.rings.get(f0, f1)
        show(ring, f0, f1)
        disc = self.discs.get(f0, f1)
        show(disc, f0, f1)
        e = align_euler(normal)
        for ob in (ring, disc):
            for fr in (f0, f1):
                key_tf(ob, fr, loc=loc, rot=e)
            key_tf(ob, f0, scale=(0.01, 0.01, 0.01))
            key_tf(ob, f0 + 6, scale=(size, size, size))
            key_tf(ob, f1 - 6, scale=(size * 1.05, size * 1.05, size))
            key_tf(ob, f1, scale=(0.01, 0.01, 0.01))
        key_col(ring, f0, PURPLE, 1.0)
        key_col(ring, f1, PURPLE, 1.0)
        key_col(disc, f0, (0.06, 0.0, 0.16), 0.92)
        key_col(disc, f1, (0.06, 0.0, 0.16), 0.92)
        self.ring(f0, loc, normal, size * 0.5, size * 2.2, 14, CYAN, 0.7, kind='glow')

    def speed_lines(self, f, center, n=8, radius=3.0, length=4.0, dur=3, color=(0.05, 0.05, 0.06)):
        center = Vector(center)
        for _ in range(n):
            d = rand_unit(self.rng)
            start = center + d * radius * self.rng.uniform(0.6, 1.2)
            ob = self.lines.get(f, f + dur)
            show(ob, f, f + dur)
            e = Vector((1, 0, 0)).rotation_difference(d).to_euler()
            ln = length * self.rng.uniform(0.6, 1.3)
            for fr in (f, f + dur):
                key_tf(ob, fr, loc=start, rot=e, scale=(ln, 1, 1))
            key_col(ob, f, color, 0.85)
            key_col(ob, f + dur, color, 0.0)

    def explosion(self, f, loc, scale=1.0, color=PURPLE, crater=True, rocks=True):
        loc = Vector(loc)
        ground = Vector((loc.x, loc.y, 0.05))
        self.burst(f, loc, 2.2 * scale, 10, color)
        self.burst(f + 1, loc, 1.4 * scale, 8, HOT)
        self.ring(f, ground, UP, 0.5 * scale, 9 * scale, 22, color, 0.85)
        self.ring(f + 2, loc, rand_unit(self.rng), 0.3 * scale, 5 * scale, 16, WHITE, 0.9)
        self.dust(f + 2, ground, 7, 1.6 * scale, 1.3 * scale, 40)
        if rocks:
            self.rocks_burst(f, ground, int(6 + 4 * scale), 7 + 3 * scale, 0.18 * scale + 0.05, 48)
        if crater and loc.z < 1.5 and (scale >= 1.4 or self.rng.random() < 0.3):
            self.crater(f, ground, 1.2 * scale, 3)
        shake(f, 0.05 * scale, 16)

    def impact(self, f, loc, direction, size=1.0, color=HOT, lines=True):
        loc = Vector(loc)
        self.burst(f, loc, 0.9 * size, 7, color)
        self.ring(f, loc + Vector(direction).normalized() * 0.4, direction, 0.2 * size, 2.6 * size, 10,
                  WHITE, 0.95)
        if lines:
            self.speed_lines(f, loc, 6, 1.2 * size + 1.0, 3.0, 3)


