class Fighter:
    def __init__(self, name, rig, coll):
        self.name, self.rig, self.coll = name, rig, coll
        self.parts = []
        self.yaw = 0.0
        self.track_f, self.track_p = [], []
        self.extra = {}

    # python-side position memory (for facing / aiming while choreographing)
    def at(self, f):
        i = bisect.bisect_right(self.track_f, f)
        if i == 0:
            return self.track_p[0].copy() if self.track_p else Vector()
        if i >= len(self.track_f):
            return self.track_p[-1].copy()
        f0, f1 = self.track_f[i - 1], self.track_f[i]
        t = (f - f0) / max(1, f1 - f0)
        return self.track_p[i - 1].lerp(self.track_p[i], t)

    def center(self, f):
        return self.at(f) + Vector((0, 0, CENTER))

    def place(self, f, loc, yaw=None, face=None, pitch=0.0, roll=0.0, interp=None):
        loc = Vector(loc)
        if face is not None:
            tgt = face.at(f) if isinstance(face, Fighter) else Vector(face)
            y = yaw_to(loc, tgt)
            yaw = y if y is not None else self.yaw
        if yaw is None:
            yaw = self.yaw
        while yaw - self.yaw > math.pi:
            yaw -= 2 * math.pi
        while yaw - self.yaw < -math.pi:
            yaw += 2 * math.pi
        self.yaw = yaw
        r = self.rig
        r.location = loc + Vector((0, 0, CENTER))
        r.rotation_euler = (pitch, roll, yaw)
        r.keyframe_insert('location', frame=f, group='Placement')
        r.keyframe_insert('rotation_euler', frame=f, group='Placement')
        i = bisect.bisect_left(self.track_f, f)
        if i < len(self.track_f) and self.track_f[i] == f:
            self.track_p[i] = loc
        else:
            self.track_f.insert(i, f)
            self.track_p.insert(i, loc)
        if interp:
            want_interp(r, 'loc', f, interp)

    def pose(self, f, name, interp=None, **ovr):
        p = dict(POSES[name])
        p.update(ovr)
        eul = pose_eulers(p)
        lift = p.get('lift')
        if lift is None:
            lift = 0.0 if p.get('air') else ground_lift(eul)
        pbs = self.rig.pose.bones
        for bname, e in eul.items():
            pb = pbs[bname]
            pb.rotation_euler = e
            pb.keyframe_insert('rotation_euler', frame=f, group=bname)
        hp = pbs['hips']
        hp.location = (-p.get('side', 0.0), lift, p.get('fwd', 0.0))
        hp.keyframe_insert('location', frame=f, group='hips')
        if interp:
            want_interp(self.rig, 'pose', f, interp)

    def set_visible(self, f, vis):
        for ob in self.parts:
            ob.hide_render = not vis
            ob.hide_viewport = not vis
            ob.keyframe_insert('hide_render', frame=f)
            ob.keyframe_insert('hide_viewport', frame=f)


def seg_part(ch, name, bone, p0, p1, r0, r1, mat, segs=14):
    p0, p1 = P(*p0), P(*p1)
    d = p1 - p0
    me = lathe(ch.name + '_' + name, capsule_profile(d.length, r0, r1), segs)
    ob = new_obj(ch.name + '_' + name, me, ch.coll)
    q = Vector((0, 0, 1)).rotation_difference(d.normalized())
    ob.matrix_basis = Matrix.Translation(p0) @ q.to_matrix().to_4x4()
    me.materials.append(mat)
    attach(ob, ch.rig, bone)
    ch.parts.append(ob)
    return ob


def blob_part(ch, name, bone, c, radii, mat, rot=(0, 0, 0), segs=18, rings=10):
    me = sphere_mesh(ch.name + '_' + name, segs, rings)
    ob = new_obj(ch.name + '_' + name, me, ch.coll)
    ob.matrix_basis = (Matrix.Translation(P(*c)) @ Euler([rad(a) for a in rot]).to_matrix().to_4x4()
                       @ Matrix.Diagonal((*radii, 1)))
    me.materials.append(mat)
    attach(ob, ch.rig, bone)
    ch.parts.append(ob)
    return ob


def band_part(ch, name, bone, z0, z1, x, r, mat, segs=20):
    """Flat-ended ring (belt, wrist band) around a vertical limb."""
    me = cylinder_mesh(ch.name + '_' + name, r, z1 - z0, segs)
    ob = new_obj(ch.name + '_' + name, me, ch.coll)
    ob.matrix_basis = Matrix.Translation(P(x, 0, z0))
    me.materials.append(mat)
    attach(ob, ch.rig, bone)
    ch.parts.append(ob)
    return ob


def box_part(ch, name, bone, c, half, mat, rot=(0, 0, 0)):
    me = box_mesh(ch.name + '_' + name, *half)
    ob = new_obj(ch.name + '_' + name, me, ch.coll)
    ob.matrix_basis = Matrix.Translation(P(*c)) @ Euler([rad(a) for a in rot]).to_matrix().to_4x4()
    me.materials.append(mat)
    attach(ob, ch.rig, bone)
    ch.parts.append(ob)
    return ob


def cone_part(ch, name, bone, base, direction, r, h, mat):
    me = cone_mesh(ch.name + '_' + name, r, h, 8)
    ob = new_obj(ch.name + '_' + name, me, ch.coll)
    q = Vector((0, 0, 1)).rotation_difference(Vector(direction).normalized())
    ob.matrix_basis = Matrix.Translation(P(*base)) @ q.to_matrix().to_4x4()
    me.materials.append(mat)
    attach(ob, ch.rig, bone)
    ch.parts.append(ob)
    return ob


