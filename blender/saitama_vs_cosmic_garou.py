def pose_eulers(p):
    out = {}
    for k in ('hips', 'spine', 'chest', 'neck', 'head'):
        b, t, s = p.get(k, (0, 0, 0))
        out[k] = (rad(b), rad(t), rad(s))
    for sd, sg in (('L', 1), ('R', -1)):
        f, o, tw = p.get('arm' + sd, (3, 7, 0))
        out['upper_arm.' + sd] = (rad(f), rad(tw) * sg, rad(o) * sg)
        out['forearm.' + sd] = (rad(p.get('fore' + sd, 10)), 0, 0)
        out['hand.' + sd] = (rad(p.get('hand' + sd, 0)), 0, 0)
        lf, lo = p.get('leg' + sd, (0, 4))
        out['thigh.' + sd] = (rad(lf), 0, rad(lo) * sg)
        out['shin.' + sd] = (-rad(p.get('knee' + sd, 0)), 0, 0)
        out['foot.' + sd] = (rad(p.get('foot' + sd, 0)), 0, 0)
    return out


REST = {}


def cache_rest(rig):
    for b in rig.data.bones:
        rel = (b.parent.matrix_local.inverted() @ b.matrix_local) if b.parent else b.matrix_local
        REST[b.name] = (b.parent.name if b.parent else None, rel, b.length)


def ground_lift(eul):
    """Tiny forward-kinematics pass: how far to lift the hips so the lowest
    foot / knee touches the floor."""
    mats = {}
    for name, _h, _t, _p, _r in BONE_DEF:
        par, rel, _ln = REST[name]
        R = Euler(eul.get(name, (0, 0, 0)), 'XYZ').to_matrix().to_4x4()
        mats[name] = (mats[par] @ rel @ R) if par else (rel @ R)
    zs = []
    for sd in 'LR':
        fm = mats['foot.' + sd]
        ln = REST['foot.' + sd][2]
        zs.append((fm @ Vector((0, 0, -0.09))).z)
        zs.append((fm @ Vector((0, ln, -0.03))).z)
        zs.append((mats['shin.' + sd] @ Vector((0, 0, 0))).z - 0.07)
    return -(min(zs) + CENTER)


