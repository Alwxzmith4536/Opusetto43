def choreograph(S, G, fx, world, cam):
    rng = random.Random(2024)
    glow = G.extra['glow'].outputs[0]

    def set_glow(f, v):
        glow.default_value = v
        glow.keyframe_insert('default_value', frame=f)

    def brows(f, serious):
        for sd, sg in (('L', 1), ('R', -1)):
            b = S.extra['brow' + sd]
            b.rotation_euler = (0, rad(24 * sg) if serious else 0, 0)
            b.keyframe_insert('rotation_euler', frame=f)

    def halo_scale(f, s):
        for ob in (G.extra['halo_pivot'], G.extra['orbiters']):
            ob.scale = (s, s, s)
            ob.keyframe_insert('scale', frame=f)

    def auto_shots(f0, f1, templates, min_len=48, max_len=84):
        f = f0
        while f <= f1:
            ln = rng.randint(min_len, max_len)
            e = min(f1, f + ln - 1)
            if f1 - e < min_len * 0.6:
                e = f1
            t = rng.choice(templates)
            a = rng.uniform(-30, 30)
            if t == 'side':
                flip = rng.choice((0, 180))
                cam.shot(f, e, ('mid', (0, 0, 0.1)), ('orbit', 'mid', a + flip, a + flip + rng.uniform(-20, 20),
                                                      6.5, 5.5, 0.5, 0.9), (35, 38))
            elif t == 'ots_S':
                cam.shot(f, e, ('G', (0, 0, 0.3)), ('rel', 'S', (0.95, -3.2, 0.75), (0.8, -2.8, 0.7)), (35, 38))
            elif t == 'ots_G':
                cam.shot(f, e, ('S', (0, 0, 0.3)), ('rel', 'G', (-0.95, -3.2, 0.75), (-0.8, -2.8, 0.7)), (35, 38))
            elif t == 'low':
                cam.shot(f, e, ('mid', (0, 0, 0.4)), ('orbit', 'mid', a, a + 25, 4.2, 3.6, -0.75, -0.6), (22, 24))
            elif t == 'wide':
                cam.shot(f, e, 'mid', ('orbit', 'mid', a + 180 * rng.randint(0, 1), a + 15, 13, 11, 3.0, 2.2), (30, 32))
            elif t == 'top':
                cam.shot(f, e, 'mid', ('orbit', 'mid', a, a + 40, 3.5, 3.0, 9, 8), (26, 26))
            elif t == 'air':
                cam.shot(f, e, 'mid', ('orbit', 'mid', a, a + rng.uniform(25, 50), 9, 7, rng.uniform(-3, 2), 0.5), (30, 34))
            f = e + 1

    # ---------------------------------------------------------------- INTRO
    Sp, Gp = Vector((-7, 0, 0)), Vector((7, 0, 0))
    S.place(1, Sp, face=Gp)
    S.pose(1, 'idle')
    G.place(1, Gp + Vector((0, 0, 0.7)), face=Sp)
    G.pose(1, 'float')
    G.set_visible(1, True)
    brows(1, False)
    set_glow(1, 0.15)
    halo_scale(1, 0.0)
    halo_scale(70, 0.0)
    for i, f in enumerate(range(24, 330, 30)):
        G.place(f, Gp + Vector((0, 0, 0.7 + 0.15 * math.sin(i * 1.4))), face=Sp)
    halo_scale(80, 1.35)
    halo_scale(92, 1.0)
    set_glow(70, 0.15)
    set_glow(92, 1.0)
    fx.ring(72, Gp + Vector((0, 0, 1.8)), (1, 0, 0), 0.3, 6, 24, CYAN, 0.9)
    fx.ring(74, Gp + Vector((0, 0, 0.05)), UP, 0.5, 10, 30, PURPLE, 0.8)
    fx.dust(76, Gp, 8, 2.0, 0.8, 34)
    shake(74, 0.04, 14)
    S.pose(140, 'idle')
    S.pose(152, 'nosepick')
    S.pose(222, 'nosepick', foreR=150)
    S.pose(236, 'idle')
    G.pose(250, 'float')
    G.pose(264, 'charge')
    for k, f in enumerate((270, 292, 314)):
        fx.ring(f, Gp + Vector((0, 0, 0.05)), UP, 0.5, 8 + 3 * k, 22, PURPLE, 0.85)
        fx.ring(f + 2, Gp + Vector((0, 0, 1.5)), rand_unit(fx.rng), 0.4, 4 + k, 16, CYAN, 0.9)
        fx.dust(f, Gp, 8, 2.2 + k, 0.7, 30)
        shake(f, 0.05 + 0.02 * k, 12)
    world.flash(316, 2)
    G.pose(332, 'float')
    G.place(334, Gp + Vector((0, 0, 0.7)), face=Sp)
    G.place(352, Gp, face=Sp)
    G.pose(352, 'stance')
    fx.dust(352, Gp, 5, 0.8, 0.5, 24)
    cam.shot(1, 110, ('mid', (0, 0, 0.2)), ('orbit', 'mid', -35, -8, 15, 12, 2.6, 1.8), (28, 30))
    cam.shot(111, 175, ('G', (0, 0, 0.75)), ('rel', 'G', (0.8, 3.4, 0.5), (0.4, 2.6, 0.45)), (45, 50))
    cam.shot(176, 245, ('S', (0, 0, 0.7)), ('rel', 'S', (-0.5, 2.3, 0.75), (-0.3, 1.8, 0.7)), (45, 50))
    cam.shot(246, 330, ('G', (0, 0, 0.6)), ('rel', 'G', (2.4, 4.2, -0.8), (3.0, 5.0, -0.7)), (22, 24))
    cam.shot(331, 384, ('mid', (0, 0, 0.1)), ('orbit', 'mid', 15, 30, 13, 11, 1.4, 1.2), (32, 35))

    # ---------------------------------------------------------------- ROUND 1
    f = 385
    G.pose(f, 'stance')
    G.place(f, Gp, face=Sp)
    G.pose(f + 4, 'dash')
    d = 1.15
    Gd = Sp + (Gp - Sp).normalized() * d
    G.place(f + 13, Gd, face=Sp)
    for k in range(5):
        fx.puff(f + 2 * k, Gp.lerp(Gd, k / 5) + Vector((0, 0, 0.2)), 0.2, 0.9, 20)
    fx.speed_lines(f + 6, Gp.lerp(Gd, 0.5) + Vector((0, 0, 1)), 8, 1.2, 5, 5)
    fx.ring(f + 14, Sp + Vector((0, 0, 1.4)) - (Gp - Sp).normalized() * 1.2, (Sp - Gp), 0.2, 3.5, 12, AIR, 0.8,
            kind='air')
    S.pose(f + 12, 'idle')
    S.pose(f + 14, 'dodge_left')
    G.pose(f + 14, 'punchR')
    f += 24

    ATTACKS = {
        'jabL': ('punchL_wind', 'punchL', 1.55), 'crossR': ('punchR_wind', 'punchR', 1.55),
        'kickR': ('guard', 'kickR', 1.6), 'roundR': ('guard', 'roundhouseR', 1.5),
        'kneeR': ('guard', 'kneeR', 1.1), 'palm': ('stance', 'palm', 1.4),
        'elbowR': ('punchR_wind', 'elbowR', 1.5), 'sweep': ('guard', 'sweep', 0.25),
        'kickL': ('guard', 'kickL', 1.6), 'uppercutR': ('punchR_wind', 'uppercutR', 1.55),
    }
    DODGE = {'jabL': ['dodge_left', 'dodge_right', 'dodge_back'], 'crossR': ['dodge_right', 'dodge_left', 'duck'],
             'kickR': ['duck', 'dodge_back'], 'kickL': ['duck', 'dodge_back'], 'roundR': ['duck'],
             'kneeR': ['dodge_back'], 'palm': ['dodge_left', 'dodge_right'], 'elbowR': ['dodge_back', 'duck'],
             'sweep': ['jump'], 'uppercutR': ['dodge_back']}

    center = (Sp + Gd) * 0.5
    theta = math.atan2((Gd - Sp).y, (Gd - Sp).x)

    def exchange(f, t_end, speed=1.0, outcome='dodge', push=0.3):
        nonlocal center, theta
        combo = 0
        while f < t_end:
            combo += 1
            n = rng.randint(3, 6)
            for k in range(n):
                if f >= t_end:
                    break
                atk = rng.choice(list(ATTACKS))
                wind, strike, h = ATTACKS[atk]
                wf = max(2, int(round(4 / speed)))
                rf = max(2, int(round(5 / speed)))
                theta += rad(rng.uniform(-14, 14))
                u = hdir(theta)
                center = center - u * push
                Gpos = center + u * d / 2
                Spos = center - u * d / 2
                G.place(f, Gpos, face=Spos)
                G.pose(f, wind)
                fs = f + wf
                G.place(fs, Gpos - u * 0.2, face=Spos)
                G.pose(fs, strike)
                hit_pt = Spos + Vector((0, 0, h))
                if outcome == 'dodge':
                    blocked = (combo % 3 == 0 and k == n - 1)
                    if blocked:
                        S.place(f, Spos, face=Gpos)
                        S.pose(f, 'idle')
                        S.pose(fs - 1, 'finger_block')
                        S.place(fs, Spos, face=Gpos)
                        fx.impact(fs, Spos + u * 0.45 + Vector((0, 0, 1.45)), u, 1.3)
                        fx.ring(fs, Spos - u * 0.8 + Vector((0, 0, 1.3)), u, 0.3, 5.5, 16, AIR, 0.8, kind='air')
                        fx.dust(fs, Spos - u * 1.5, 6, 1.5, 0.8, 30)
                        fx.crater(fs, Spos - u * 0.2, 0.9, 3)
                        shake(fs, 0.14, 14)
                        G.place(fs + 8, Gpos + u * 1.6, face=Spos)
                        G.pose(fs + 8, 'hit', interp=None)
                        center = center + u * 0.8
                        S.pose(fs + 14, 'idle')
                        f = fs + 16
                        continue
                    dg = rng.choice(DODGE[atk])
                    S.place(f, Spos, face=Gpos)
                    S.pose(fs - 1, dg)
                    if dg == 'jump':
                        S.place(fs, Spos + Vector((0, 0, 0.7)), face=Gpos)
