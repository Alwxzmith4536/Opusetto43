def _tree(mat):
    try:
        mat.use_nodes = True
    except Exception:
        pass
    nt = mat.node_tree
    nt.nodes.clear()
    return nt


def _out(nt, shader_socket):
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    nt.links.new(shader_socket, out.inputs['Surface'])
    return out


def _set_render_method(mat, blended):
    if hasattr(mat, 'surface_render_method'):
        mat.surface_render_method = 'BLENDED' if blended else 'DITHERED'
    elif hasattr(mat, 'blend_method'):
        mat.blend_method = 'BLEND' if blended else 'OPAQUE'
        if hasattr(mat, 'shadow_method'):
            mat.shadow_method = 'NONE' if blended else 'OPAQUE'


def toon_mat(name, color, shade=0.62, shade_tint=(1.0, 1.0, 1.0)):
    """Two-tone cel shading: lit colour / shadow colour, flat like anime."""
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1)
    nt = _tree(mat)
    diff = nt.nodes.new('ShaderNodeBsdfDiffuse')
    s2r = nt.nodes.new('ShaderNodeShaderToRGB')
    nt.links.new(diff.outputs[0], s2r.inputs[0])
    ramp = nt.nodes.new('ShaderNodeValToRGB')
    ramp.color_ramp.interpolation = 'CONSTANT'
    e0, e1 = ramp.color_ramp.elements[0], ramp.color_ramp.elements[1]
    e0.position, e0.color = 0.0, (shade * shade_tint[0], shade * shade_tint[1], shade * shade_tint[2], 1)
    e1.position, e1.color = 0.42, (1, 1, 1, 1)
    nt.links.new(s2r.outputs['Color'], ramp.inputs['Fac'])
    mul = nt.nodes.new('ShaderNodeVectorMath')
    mul.operation = 'MULTIPLY'
    mul.inputs[0].default_value = color
    nt.links.new(ramp.outputs['Color'], mul.inputs[1])
    em = nt.nodes.new('ShaderNodeEmission')
    em.inputs['Strength'].default_value = 1.0
    nt.links.new(mul.outputs[0], em.inputs['Color'])
    _out(nt, em.outputs[0])
    _set_render_method(mat, False)
    return mat


def glow_mat(name, color, strength=4.0):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1)
    nt = _tree(mat)
    em = nt.nodes.new('ShaderNodeEmission')
    em.inputs['Color'].default_value = (*color, 1)
    em.inputs['Strength'].default_value = strength
    _out(nt, em.outputs[0])
    return mat


def _mix_rgb(nt, blend='MIX'):
    m = nt.nodes.new('ShaderNodeMix')
    m.data_type = 'RGBA'
    m.blend_type = blend
    a = [s for s in m.inputs if s.name == 'A' and s.type == 'RGBA'][0]
    b = [s for s in m.inputs if s.name == 'B' and s.type == 'RGBA'][0]
    o = [s for s in m.outputs if s.type == 'RGBA'][0]
    return m, m.inputs[0], a, b, o


def cosmic_mat(name):
    """Garou's cosmic body: dark nebula + star field + cyan rim. 'Glow' node is animated."""
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (0.08, 0.04, 0.2, 1)
    nt = _tree(mat)
    tc = nt.nodes.new('ShaderNodeTexCoord')
    noise = nt.nodes.new('ShaderNodeTexNoise')
    noise.inputs['Scale'].default_value = 3.0
    noise.inputs['Detail'].default_value = 6.0
    nt.links.new(tc.outputs['Object'], noise.inputs['Vector'])
    neb = nt.nodes.new('ShaderNodeValToRGB')
    els = neb.color_ramp.elements
    els[0].position, els[0].color = 0.35, (0.004, 0.002, 0.02, 1)
    els[1].position, els[1].color = 0.78, (0.35, 0.18, 0.95, 1)
    mid = els.new(0.55)
    mid.color = (0.06, 0.02, 0.28, 1)
    mid2 = els.new(0.66)
    mid2.color = (0.02, 0.18, 0.55, 1)
    nt.links.new(noise.outputs['Fac'], neb.inputs['Fac'])
    vor = nt.nodes.new('ShaderNodeTexVoronoi')
    vor.inputs['Scale'].default_value = 30.0
    nt.links.new(tc.outputs['Object'], vor.inputs['Vector'])
    star = nt.nodes.new('ShaderNodeMath')
    star.operation = 'LESS_THAN'
    star.inputs[1].default_value = 0.075
    nt.links.new(vor.outputs['Distance'], star.inputs[0])
    m1, fac1, a1, b1, o1 = _mix_rgb(nt)
    nt.links.new(star.outputs[0], fac1)
    nt.links.new(neb.outputs['Color'], a1)
    b1.default_value = (1, 1, 1, 1)
    lw = nt.nodes.new('ShaderNodeLayerWeight')
    lw.inputs['Blend'].default_value = 0.35
    rimp = nt.nodes.new('ShaderNodeMath')
    rimp.operation = 'POWER'
    rimp.inputs[1].default_value = 2.5
    nt.links.new(lw.outputs['Facing'], rimp.inputs[0])
    m2, fac2, a2, b2, o2 = _mix_rgb(nt)
    nt.links.new(rimp.outputs[0], fac2)
    nt.links.new(o1, a2)
    b2.default_value = (0.45, 0.85, 1.0, 1)
    glow = nt.nodes.new('ShaderNodeValue')
    glow.name = glow.label = 'Glow'
    glow.outputs[0].default_value = 1.0
    strength = nt.nodes.new('ShaderNodeMath')
    strength.operation = 'MULTIPLY_ADD'
    strength.inputs[1].default_value = 1.6
    strength.inputs[2].default_value = 0.6
    nt.links.new(glow.outputs[0], strength.inputs[0])
    em = nt.nodes.new('ShaderNodeEmission')
    nt.links.new(o2, em.inputs['Color'])
    nt.links.new(strength.outputs[0], em.inputs['Strength'])
    _out(nt, em.outputs[0])
    _set_render_method(mat, False)
    return mat


def fx_mat(name, strength):
    """Colour + alpha come from the object's Color property, so one material
    serves every effect and each object can fade on its own."""
    mat = bpy.data.materials.new(name)
    nt = _tree(mat)
    oi = nt.nodes.new('ShaderNodeObjectInfo')
    em = nt.nodes.new('ShaderNodeEmission')
    em.inputs['Strength'].default_value = strength
    nt.links.new(oi.outputs['Color'], em.inputs['Color'])
    tr = nt.nodes.new('ShaderNodeBsdfTransparent')
    mix = nt.nodes.new('ShaderNodeMixShader')
    nt.links.new(oi.outputs['Alpha'], mix.inputs[0])
    nt.links.new(tr.outputs[0], mix.inputs[1])
    nt.links.new(em.outputs[0], mix.inputs[2])
    _out(nt, mix.outputs[0])
    _set_render_method(mat, True)
    return mat


