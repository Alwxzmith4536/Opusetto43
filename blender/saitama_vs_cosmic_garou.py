def smooth(u):
    return u * u * (3 - 2 * u)


def bake_camera(camrig, fighters):
    ev = {k: Evaluator(ch.rig) for k, ch in fighters.items()}

    def pos(spec, f):
        if isinstance(spec, tuple) and len(spec) == 2 and isinstance(spec[0], str):
            return pos(spec[0], f) + Vector(spec[1])
        if spec == 'mid':
            return (ev['S'].loc(f) + ev['G'].loc(f)) * 0.5
        if spec in ev:
            return ev[spec].loc(f)
        return Vector(spec)

    shots = sorted(camrig.shots, key=lambda s: s[0])
    for f0, f1, target, cam, lens, ease in shots:
        frames = list(range(f0, f1 + 1, 2))
        if frames[-1] != f1:
            frames.append(f1)
        kind = cam[0]
        base = 0.0
        if kind == 'orbit':
            d = ev['G'].loc(f0) - ev['S'].loc(f0)
            base = math.atan2(d.y, d.x) + math.pi / 2 if d.xy.length > 1e-3 else 0.0
            if len(cam) > 8:
                base += rad(cam[8])
        for f in frames:
            u = (f - f0) / max(1, f1 - f0)
            ue = smooth(u) if ease else u
            T = pos(target, f)
            if kind == 'orbit':
                _, center, a0, a1, r0, r1, h0, h1 = cam[:8]
                C = pos(center, f)
                a = base + rad(a0 + (a1 - a0) * ue)
                r = r0 + (r1 - r0) * ue
                if center == 'mid' or (isinstance(center, tuple) and center[0] == 'mid'):
                    sep = (ev['S'].loc(f) - ev['G'].loc(f)).length
                    r = max(r, 0.85 * sep + 1.5)
                h = h0 + (h1 - h0) * ue
                cp = C + Vector((math.cos(a) * r, math.sin(a) * r, h))
            elif kind == 'rel':
                _, who, o0, o1 = cam
                rz = ev[who].rot(f).z
                o = Vector(o0).lerp(Vector(o1), ue)
                cp = ev[who].loc(f) + Matrix.Rotation(rz, 3, 'Z') @ o
            elif kind == 'follow':
                _, who, o0, o1 = cam
                cp = pos(who, f) + Vector(o0).lerp(Vector(o1), ue)
            else:  # fixed
                _, p0, p1 = cam
                cp = Vector(p0).lerp(Vector(p1), ue)
            cp.z = max(cp.z, 0.25)
            camrig.rig.location = cp
            camrig.rig.keyframe_insert('location', frame=f)
            camrig.target.location = T
            camrig.target.keyframe_insert('location', frame=f)
            camrig.data.lens = lens[0] + (lens[1] - lens[0]) * ue
            camrig.data.keyframe_insert('lens', frame=f)
    for idb in (camrig.rig, camrig.target, camrig.data):
        set_all_interp(idb, 'LINEAR')

    # camera shake
    rng = random.Random(77)
    amp = [0.0] * (END + 2)
    for f, s, dur in SHAKES:
        for k in range(dur):
            if 0 < f + k <= END:
                amp[f + k] += s * (1 - k / dur) ** 2
    sh = camrig.shaker
    active = False
    for f in range(1, END + 1):
        a = min(amp[f], 0.6)
        if a > 0.002:
            sh.location = (rng.uniform(-a, a), rng.uniform(-a, a), rng.uniform(-a, a) * 0.6)
            sh.keyframe_insert('location', frame=f)
            active = True
        elif active:
            sh.location = (0, 0, 0)
            sh.keyframe_insert('location', frame=f)
            active = False
    set_all_interp(sh, 'LINEAR')


def bake_cape(ch, f0=1, f1=END):
    ev = Evaluator(ch.rig)
    pbs = [ch.rig.pose.bones[b[0]] for b in CAPE_BONES]
    prev = ev.loc(f0)
    for f in range(f0, f1 + 1, 3):
        cur = ev.loc(f)
        v = (cur - prev) * (FPS / 3.0)
        prev = cur
        yaw = ev.rot(f).z
        vf = v.dot(fwd(yaw))
        vs = v.dot(side_vec(yaw))
        speed = v.length
        flow = min(80.0, 9 + max(0.0, vf) * 5 + max(0.0, -v.z) * 5 + speed * 1.2)
        if vf < -1.0:
            flow = max(4.0, flow - (-vf) * 3)
        wob = 3 + min(9.0, speed * 0.6)
        for i, pb in enumerate(pbs):
            ph = f * 0.33 - i * 0.9
            ang = -flow * (0.45, 0.3, 0.25)[i] + math.sin(ph) * wob * (0.4, 0.7, 1.0)[i]
            sway = math.sin(ph * 0.7 + 1.3) * wob * 0.5 * (i + 1) / 3 - max(-20, min(20, vs * 3)) * (0.2, 0.3, 0.3)[i]
            pb.rotation_euler = (rad(ang), 0, rad(sway))
            pb.keyframe_insert('rotation_euler', frame=f, group='cape')


