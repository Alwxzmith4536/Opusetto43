def finish_mesh(name, verts, faces, smooth=True):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], [], faces)
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(me)
    bm.free()
    me.update()
    me.polygons.foreach_set('use_smooth', [smooth] * len(me.polygons))
    return me


def lathe(name, profile, segs=16, smooth=True):
    """Revolve a (z, r) profile around Z. r == 0 makes a pole."""
    verts, rings = [], []
    for z, r in profile:
        if r <= 1e-6:
            rings.append([len(verts)])
            verts.append((0, 0, z))
        else:
            ring = []
            for i in range(segs):
                a = 2 * math.pi * i / segs
                ring.append(len(verts))
                verts.append((r * math.cos(a), r * math.sin(a), z))
            rings.append(ring)
    faces = []
    for A, B in zip(rings, rings[1:]):
        if len(A) == 1 and len(B) == 1:
            continue
        if len(A) == 1:
            for i in range(segs):
                faces.append((A[0], B[(i + 1) % segs], B[i]))
        elif len(B) == 1:
            for i in range(segs):
                faces.append((A[i], A[(i + 1) % segs], B[0]))
        else:
            for i in range(segs):
                faces.append((A[i], A[(i + 1) % segs], B[(i + 1) % segs], B[i]))
    if len(rings[0]) > 1:
        faces.append(tuple(reversed(rings[0])))
    if len(rings[-1]) > 1:
        faces.append(tuple(rings[-1]))
    return finish_mesh(name, verts, faces, smooth)


def capsule_profile(L, r0, r1, n=5):
    prof = []
    for i in range(n + 1):
        a = -math.pi / 2 + (math.pi / 2) * i / n
        prof.append((r0 * math.sin(a), r0 * math.cos(a)))
    for i in range(n + 1):
        a = (math.pi / 2) * i / n
        prof.append((L + r1 * math.sin(a), r1 * math.cos(a)))
    return prof


def sphere_mesh(name, segs=18, rings=10):
    prof = []
    for i in range(rings + 1):
        a = -math.pi / 2 + math.pi * i / rings
        prof.append((math.sin(a), math.cos(a)))
    return lathe(name, prof, segs)


def cone_mesh(name, r=1.0, h=1.0, segs=10):
    return lathe(name, [(0, 0), (0, r), (h, 0)], segs, smooth=False)


def cylinder_mesh(name, r=1.0, h=1.0, segs=16):
    return lathe(name, [(0, 0), (0, r), (h, r), (h, 0)], segs, smooth=True)


def torus_mesh(name, R=1.0, r=0.05, seg=48, rseg=8):
    verts, faces = [], []
    for i in range(seg):
        a = 2 * math.pi * i / seg
        for j in range(rseg):
            b = 2 * math.pi * j / rseg
            rr = R + r * math.cos(b)
            verts.append((rr * math.cos(a), rr * math.sin(a), r * math.sin(b)))
    for i in range(seg):
        for j in range(rseg):
            i2, j2 = (i + 1) % seg, (j + 1) % rseg
            faces.append((i * rseg + j, i2 * rseg + j, i2 * rseg + j2, i * rseg + j2))
    return finish_mesh(name, verts, faces)


def box_mesh(name, sx, sy, sz, center=(0, 0, 0)):
    cx, cy, cz = center
    verts = [(cx + x * sx, cy + y * sy, cz + z * sz)
             for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)]
    faces = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    return finish_mesh(name, verts, faces, smooth=False)


def disc_mesh(name, r=1.0, segs=32):
    verts = [(0, 0, 0)] + [(r * math.cos(2 * math.pi * i / segs), r * math.sin(2 * math.pi * i / segs), 0)
                           for i in range(segs)]
    faces = [(0, 1 + i, 1 + (i + 1) % segs) for i in range(segs)]
    return finish_mesh(name, verts, faces, smooth=False)


def rock_mesh(name, rng):
    bm = bmesh.new()
    try:
        bmesh.ops.create_icosphere(bm, subdivisions=1, radius=1.0)
    except TypeError:
        bmesh.ops.create_icosphere(bm, subdivisions=1, diameter=1.0)
    for v in bm.verts:
        v.co *= rng.uniform(0.65, 1.15)
        v.co.z *= 0.7
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    return me


def spikes_mesh(name, n=22, rng=None):
    rng = rng or random.Random(3)
    verts, faces = [], []
    for _ in range(n):
        d = rand_unit(rng)
        u = d.orthogonal().normalized()
        w = d.cross(u).normalized()
        length = rng.uniform(0.6, 1.0)
        width = rng.uniform(0.05, 0.09)
        base = len(verts)
        c = d * 0.1
        for su, sw in ((1, 1), (-1, 1), (-1, -1), (1, -1)):
            verts.append(c + u * su * width + w * sw * width)
        verts.append(d * length)
        faces += [(base, base + 1, base + 4), (base + 1, base + 2, base + 4),
                  (base + 2, base + 3, base + 4), (base + 3, base, base + 4),
                  (base + 3, base + 2, base + 1, base)]
    return finish_mesh(name, verts, faces, smooth=False)


