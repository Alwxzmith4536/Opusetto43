def mirror_pose(p):
    m = {}
    for k, v in p.items():
        if k.endswith('L') and k[:-1] in ('arm', 'fore', 'hand', 'leg', 'knee', 'foot'):
            m[k[:-1] + 'R'] = v
        elif k.endswith('R') and k[:-1] in ('arm', 'fore', 'hand', 'leg', 'knee', 'foot'):
            m[k[:-1] + 'L'] = v
        elif k in ('hips', 'spine', 'chest', 'neck', 'head'):
            m[k] = (v[0], -v[1], -v[2])
        elif k == 'side':
            m[k] = -v
        else:
            m[k] = v
    return m


