def build_armature(name, coll, with_cape=False):
    ad = bpy.data.armatures.new(name + '_Rig')
    ob = new_obj(name, ad, coll)
    ob.show_in_front = False
    ad.display_type = 'STICK'
    vl = bpy.context.view_layer
    for o in bpy.context.scene.objects:
        if o is not None:
            o.select_set(False)
    vl.objects.active = ob
    ob.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    for n, h, t, par, roll in BONE_DEF + (CAPE_BONES if with_cape else []):
        eb = ad.edit_bones.new(n)
        eb.head, eb.tail = P(*h), P(*t)
        eb.align_roll(Vector((0, 1, 0)) if roll == 'Y' else Vector((0, 0, 1)))
        if par:
            eb.parent = ad.edit_bones[par]
            eb.use_connect = False
    bpy.ops.object.mode_set(mode='OBJECT')
    ob.select_set(False)
    for pb in ob.pose.bones:
        pb.rotation_mode = 'XYZ'
    return ob


def attach(part, rig, bone):
    part.parent = rig
    part.parent_type = 'BONE'
    part.parent_bone = bone
    b = rig.data.bones[bone]
    part.matrix_parent_inverse = (b.matrix_local @ Matrix.Translation((0, b.length, 0))).inverted()


